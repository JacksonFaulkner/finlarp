/// Draws `head` (amber) and `notes` (light) wrapped across the bottom of `img`. Text too long for
/// the bottom half of the frame is cut off.
pub fn overlay(img: &mut RgbaImage, head: &str, notes: &[String]) {
    let (w, h) = img.dimensions();
    if w < 80 || h < 60 {
        return;
    }
    let s = (h / 300).max(1);
    let adv = 6 * s;
    let pitch = 10 * s;
    let pad = 8 * s;
    let max_chars = ((w - 2 * pad) / adv).max(8) as usize;
    let mut lines: Vec<(String, [u8; 3])> = Vec::new();
    for l in wrap(head, max_chars) {
        lines.push((l, HEAD));
    }
    for n in notes {
        for l in wrap(n, max_chars) {
            lines.push((l, INK));
        }
    }
    let room = ((h / 2).saturating_sub(2 * pad) / pitch) as usize;
    lines.truncate(room.max(1));
    let plate_h = lines.len() as u32 * pitch + 2 * pad;
    let y0 = h - plate_h;
    for y in y0..h {
        for x in 0..w {
            blend(img, x, y, PLATE, PLATE_A);
        }
    }
    for (i, (line, col)) in lines.iter().enumerate() {
        draw_text(img, pad, y0 + pad + i as u32 * pitch, line, s, *col);
    }
}

/// Upper-cased words, joined to at most `max` characters a line. A word longer than a line is cut.
pub fn wrap(text: &str, max: usize) -> Vec<String> {
    let max = max.max(1);
    let mut out = Vec::new();
    let mut cur = String::new();
    for word in text.split_whitespace() {
        let word = word.to_ascii_uppercase();
        let mut rest = word.as_str();
        while rest.chars().count() > max {
            if !cur.is_empty() {
                out.push(std::mem::take(&mut cur));
            }
            let cut: String = rest.chars().take(max).collect();
            out.push(cut);
            rest = &rest[rest.char_indices().nth(max).map_or(rest.len(), |(i, _)| i)..];
        }
        if rest.is_empty() {
            continue;
        }
        let need = if cur.is_empty() { rest.chars().count() } else { cur.chars().count() + 1 + rest.chars().count() };
        if need > max && !cur.is_empty() {
            out.push(std::mem::take(&mut cur));
        }
        if !cur.is_empty() {
            cur.push(' ');
        }
        cur.push_str(rest);
    }
    if !cur.is_empty() || out.is_empty() {
        out.push(cur);
    }
    out
}

fn blend(img: &mut RgbaImage, x: u32, y: u32, col: [u8; 3], a: f32) {
    let p = img.get_pixel_mut(x, y);
    for k in 0..3 {
        p.0[k] = (p.0[k] as f32 * (1.0 - a) + col[k] as f32 * a).round() as u8;
    }
}

fn draw_text(img: &mut RgbaImage, x0: u32, y0: u32, text: &str, s: u32, col: [u8; 3]) {
    let (w, h) = img.dimensions();
    for (i, c) in text.chars().enumerate() {
        let rows = glyph(c);
        let gx = x0 + i as u32 * 6 * s;
        for (ry, bits) in rows.iter().take(7).enumerate() {
            for rx in 0..5u32 {
                if (*bits >> (4 - rx)) & 1 == 0 {
                    continue;
                }
                for sy in 0..s {
                    for sx in 0..s {
                        let (x, y) = (gx + rx * s + sx, y0 + ry as u32 * s + sy);
                        if x < w && y < h {
                            img.get_pixel_mut(x, y).0 = [col[0], col[1], col[2], 255];
                        }
                    }
                }
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn wrap_keeps_lines_short_and_words_whole() {
        let lines = wrap("the quick brown fox jumps over the lazy dog", 12);
        assert!(lines.iter().all(|l| l.chars().count() <= 12), "{lines:?}");
        assert_eq!(lines.join(" "), "THE QUICK BROWN FOX JUMPS OVER THE LAZY DOG");
    }

    #[test]
    fn wrap_cuts_a_word_longer_than_a_line() {
        let lines = wrap("supercalifragilistic", 8);
        assert!(lines.iter().all(|l| l.chars().count() <= 8), "{lines:?}");
    }

    #[test]
    fn overlay_draws_text_on_the_foot_of_the_frame() {
        let mut img = RgbaImage::from_pixel(400, 240, image::Rgba([40, 42, 52, 255]));
        overlay(&mut img, "caption here", &["what: a note".to_string()]);
        let amber = img.pixels().any(|p| p.0[0] == HEAD[0] && p.0[1] == HEAD[1] && p.0[2] == HEAD[2]);
        assert!(amber, "the caption is drawn in amber");
        // the top of the frame is untouched
        assert_eq!(img.get_pixel(200, 5).0, [40, 42, 52, 255]);
    }
}
