"""Build the x-diagrams Terms tab from tui/src/screens/diagrams_pages/terms/.

Each term is three files sharing a slug (e.g. TRM_CXL):
  TRM_CXL.json      {"label": "CXL", "term": "CXL", "aliases": [...], "kind": "memory"}
  TRM_CXL.desc.txt  short description (popup text)
  TRM_CXL.txt       the node page (box-drawing art + "# 1. ..." sections)

Writes:
  tui/src/screens/diagrams_terms_gen.rs   TERM_DESCS, TERM_VISUALS, TERMS_ART
  py/derive/lsp_terms_seed.json           node = label for each term (adds missing terms)

Run: python py/tools/terms_gen.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIR = ROOT / "tui/src/screens/diagrams_pages/terms"
GEN = ROOT / "tui/src/screens/diagrams_terms_gen.rs"
NODES_RS = ROOT / "tui/src/screens/diagrams_terms_nodes.rs"
SPECS = ROOT / "tools/pbr3d/specs/terms"
GLBS = ROOT / "tools/pbr3d/assets"
SEED = ROOT / "py/derive/lsp_terms_seed.json"

COLS = 5
BOX_W = 24  # inner width


def load() -> list[tuple[str, dict]]:
    out = []
    for j in sorted(DIR.glob("*.json")):
        slug = j.stem
        if not (DIR / f"{slug}.desc.txt").exists() or not (DIR / f"{slug}.txt").exists():
            print(f"skip {slug}: missing .desc.txt or .txt")
            continue
        meta = json.loads(j.read_text())
        meta["label"] = meta.get("label", meta["term"]).upper()[:BOX_W - 2]
        out.append((slug, meta))
    return out


def art(terms: list[tuple[str, dict]]) -> str:
    by_kind: dict[str, list[dict]] = {}
    for _, m in terms:
        by_kind.setdefault(m.get("kind", "other"), []).append(m)
    lines = ["# Terms: one box per filing word (enter opens it; gd in a filing lands here)", ""]
    for kind in sorted(by_kind):
        ms = sorted(by_kind[kind], key=lambda m: m["label"])
        lines.append(f"# {kind}")
        for i in range(0, len(ms), COLS):
            row = ms[i : i + COLS]
            top = "  ".join("┌" + "─" * BOX_W + "┐" for _ in row)
            mid = "  ".join("│ " + m["label"].ljust(BOX_W - 1) + "│" for m in row)
            bot = "  ".join("└" + "─" * BOX_W + "┘" for _ in row)
            lines += ["  " + top, "  " + mid, "  " + bot]
        lines.append("")
    return "\n".join(lines) + "\n"


def rs(terms: list[tuple[str, dict]], art_text: str) -> str:
    def table(name: str, ext: str) -> str:
        rows = "".join(
            f'    ({json.dumps(m["label"])}, include_str!("diagrams_pages/terms/{s}{ext}")),\n'
            for s, m in terms
        )
        return f"pub const {name}: &[(&str, &str)] = &[\n{rows}];\n"

    return (
        "// GENERATED by py/tools/terms_gen.py from diagrams_pages/terms/. Do not edit.\n\n"
        + table("TERM_DESCS", ".desc.txt")
        + "\n"
        + table("TERM_VISUALS", ".txt")
        + "\n/// Page slug -> box label (the LSP seed names terms by slug).\npub const TERM_SLUGS: &[(&str, &str)] = &[\n"
        + "".join(f'    ("{s}", {json.dumps(m["label"])}),\n' for s, m in terms)
        + "];\n"
        + "\npub const TERMS_ART: &str = "
        + "r#\"" + art_text + "\"#;\n"
    )


def _lit(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def nodes_rs(terms: list[tuple[str, dict]]) -> str:
    """One node per term with a spec and a GLB: its overview is the term's Blender scene."""
    out = [
        "// GENERATED by py/tools/terms_gen.py from tools/pbr3d/specs/terms and assets. Do not edit.",
        "",
        "use super::diagrams_nodes::Node;",
        "use super::diagrams_nodes::blender::{BEAT_MS, Cell, Page};",
        "use crate::ui::anim::{Beat, Scene};",
        "",
    ]
    entries = []
    for i, (slug, meta) in enumerate(terms):
        spec_path = SPECS / f"{slug}.json"
        glb = GLBS / f"term_{slug}.glb"
        if not spec_path.exists() or not glb.exists():
            continue
        spec = json.loads(spec_path.read_text())
        desc = (DIR / f"{slug}.desc.txt").read_text().strip()
        label = meta["label"]
        beats = []
        for b in spec["beats"]:
            cap = b.get("caption") or label.lower()
            beats.append(
                f"    Beat::new({_lit(cap)}, BEAT_MS)\n"
                f"        .note({_lit(b.get('text') or desc)}, {_lit(cap)})\n"
                f"        .detail({_lit(label.lower())}, &[{_lit(label)}]),\n"
            )
        out += [
            f"static C{i}: Cell = std::sync::OnceLock::new();",
            f"const B{i}: &[Beat] = &[",
            *beats,
            "];",
            f"fn b{i}() -> Box<dyn Scene> {{",
            f"    Box::new(Page {{ cell: &C{i}, glb: include_bytes!(\"../../../tools/pbr3d/assets/term_{slug}.glb\"), beats: B{i}, zooms: &[] }})",
            "}",
            "",
        ]
        entries.append(f"    Node {{ page: {_lit(label)}, overview: Some(b{i}), sections: &[], clips: false }},")
    out += ["pub const NODES: &[Node] = &[", *entries, "];", ""]
    return "\n".join(out)


def seed(terms: list[tuple[str, dict]]) -> None:
    data = json.loads(SEED.read_text())
    by_term = {t["term"].lower(): t for t in data}
    for slug, m in terms:
        t = by_term.get(m["term"].lower())
        if t is None:
            t = {"term": m["term"], "aliases": [], "node": None, "kind": m.get("kind", "other")}
            data.append(t)
            by_term[m["term"].lower()] = t
        for a in m.get("aliases", []):
            if a not in t["aliases"] and a != t["term"]:
                t["aliases"].append(a)
        if not t.get("node") or t["node"] == m["label"]:
            t["node"] = slug
    SEED.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")


def main() -> None:
    terms = load()
    a = art(terms)
    GEN.write_text(rs(terms, a))
    NODES_RS.write_text(nodes_rs(terms))
    seed(terms)
    print(f"{len(terms)} terms -> {GEN.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
